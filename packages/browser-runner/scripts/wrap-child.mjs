// Wraps the esbuild child bundle as a generated TS module and removes the temp
// file. Run from the package root by `pnpm run build:child`.
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const tmpPath = join(root, "src", "child-bundle.tmp.js");
const genPath = join(root, "src", "child-bundle.gen.ts");

const bundle = readFileSync(tmpPath, "utf8");
writeFileSync(
	genPath,
	`// Generated by \`pnpm run build:child\`. Do not edit by hand.\n\nexport const CHILD_BUNDLE_JS = ${JSON.stringify(bundle)};\n`,
);
rmSync(tmpPath);
console.log(`child bundle: ${bundle.length} chars -> ${genPath}`);
