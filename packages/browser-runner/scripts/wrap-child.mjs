// Wraps the esbuild child bundle as a generated TS module and removes the temp
// file. Pass an absolute input path when the bundle was built outside the repo.
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const tmpPath = process.argv[2] ?? join(root, "src", "child-bundle.tmp.js");
if (!isAbsolute(tmpPath)) throw new Error("The child bundle input path must be absolute.");
const genPath = join(root, "src", "child-bundle.gen.ts");

const bundle = readFileSync(tmpPath, "utf8");
writeFileSync(
	genPath,
	`// Generated by \`pnpm run build:child\`. Do not edit by hand.\n\nexport const CHILD_BUNDLE_JS = ${JSON.stringify(bundle)};\n`,
);
rmSync(tmpPath);
console.log(`child bundle: ${bundle.length} chars -> ${genPath}`);
